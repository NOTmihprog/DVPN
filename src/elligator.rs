//! Elligator2 for handshake ephemerals (PLAN §4.1): the 32 bytes of an ephemeral public key on the
//! wire are replaced by its Elligator2 representative, which is indistinguishable from random
//! bytes. A plain X25519 public key is not: it is always a valid curve point, and a fixed-place
//! field of valid points is a signature.
//!
//! Built on `curve25519-elligator2` (the arti/obfs4 implementation), `Randomized` variant:
//! - only about half of the keys have a representative, so key generation retries;
//! - the public key gets a random low-order component ("dirty" key), otherwise every decoded
//!   representative would be a point of prime order, which random strings are only 1/8 of the
//!   time. X25519 clamps the scalar to a multiple of 8, so this does not change shared secrets;
//! - the two unused top bits of the representative are random (the `tweak`);
//! - encoding and decoding are constant time in the library.

use curve25519_elligator2::{MapToPointVariant, MontgomeryPoint, Randomized};
use x25519_dalek::StaticSecret;

use crate::crypto::random_bytes;
use crate::noise::Ephemeral;

/// With a good RNG each try succeeds with probability ~1/2; 128 failures in a row means a broken RNG.
const MAX_TRIES: usize = 128;

/// A fresh ephemeral key pair and the representative to send in place of its public key.
pub fn ephemeral() -> (Ephemeral, [u8; 32]) {
    for _ in 0..MAX_TRIES {
        let private: [u8; 32] = random_bytes();
        let tweak: u8 = rand::random();
        let repr: Option<[u8; 32]> = Randomized::to_representative(&private, tweak).into();
        if let Some(repr) = repr {
            let public = Randomized::mul_base_clamped(private).to_montgomery().to_bytes();
            return (Ephemeral { secret: StaticSecret::from(private), public }, repr);
        }
    }
    panic!("no Elligator2-representable key in {MAX_TRIES} tries: the RNG is broken");
}

/// The public key a representative stands for. Every 32-byte string decodes to some point.
pub fn public(repr: &[u8; 32]) -> [u8; 32] {
    MontgomeryPoint::from_representative::<Randomized>(repr).expect("every representative maps to a point").to_bytes()
}

