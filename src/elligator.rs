    #[test]
    fn obfs4_vectors() {
        for (i, [private, clean, dirty, repr]) in OBFS4_VECTORS.iter().enumerate() {
            let private = hex32(private);
            // the clean public key is what x25519-dalek computes
            let clean_x = PublicKey::from(&StaticSecret::from(private)).to_bytes();
            assert_eq!(clean_x, hex32(clean), "vector {i}: clean public");
            let dirty_pub = Randomized::mul_base_clamped(private).to_montgomery().to_bytes();
            assert_eq!(dirty_pub, hex32(dirty), "vector {i}: dirty public");
            let r: Option<[u8; 32]> = Randomized::to_representative(&private, 0).into();
            assert_eq!(r, Some(hex32(repr)), "vector {i}: representative");
            assert_eq!(public(&hex32(repr)), hex32(dirty), "vector {i}: decode");
        }
    }

    #[test]
    fn round_trip_and_tweak_bits_ignored() {
        for _ in 0..64 {
            let (e, repr) = ephemeral();
            assert_eq!(public(&repr), e.public);
            let mut flipped = repr;
            flipped[31] ^= 0xc0; // the two random top bits carry no information
            assert_eq!(public(&flipped), e.public);
        }
    }

    #[test]
    fn dirty_keys_give_the_same_shared_secret() {
        let (a, _) = ephemeral();
        let (b, _) = ephemeral();
        let ab = a.secret.diffie_hellman(&PublicKey::from(b.public));
        let ba = b.secret.diffie_hellman(&PublicKey::from(a.public));
        assert_eq!(ab.as_bytes(), ba.as_bytes());
        let b_clean = PublicKey::from(&b.secret);
        assert_ne!(b_clean.to_bytes(), b.public, "low-order component present");
        assert_eq!(a.secret.diffie_hellman(&b_clean).as_bytes(), ab.as_bytes());
    }

    /// Representatives on the wire should look uniform: every bit, including the two top
    /// ones that a naive implementation leaves at zero, is set about half the time.
    #[test]
    fn representative_bits_look_uniform() {
        const N: usize = 2000;
        let mut ones = [0usize; 256];
        for _ in 0..N {
            let (_, r) = ephemeral();
            for (bit, count) in ones.iter_mut().enumerate() {
                *count += ((r[bit / 8] >> (bit % 8)) & 1) as usize;
            }
        }
        // binomial(2000, 1/2): sd ~22; 6 sd keeps false failures negligible across 256 bits
        for (bit, &c) in ones.iter().enumerate() {
            assert!((N / 2).abs_diff(c) < 135, "bit {bit} set {c} of {N} times");
        }
    }
